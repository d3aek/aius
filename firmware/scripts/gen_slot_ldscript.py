"""PlatformIO pre-script: derive a slot ldscript from the canonical copy.

The A/B slot envs (aius-ota-resilience.md Phase 3b) link the identical image
at slot A's or slot B's base. Rather than committing three drifting copies of
the framework-derived ldscript, this script reads the ONE canonical
link/aius_teensy41.ld (whose body test_ldscript_drift.py keeps honest),
rewrites exactly the FLASH memory line to the slot window named by
lib/aius_ab/include/aius_ab_layout.h, and points the build at the result in
$BUILD_DIR. The slot geometry is parsed OUT OF the layout header, so the
partition arithmetic keeps its single home.
"""

import re
from pathlib import Path

Import("env")  # noqa: F821  (PlatformIO construction environment)

FIRMWARE_ROOT = Path(env["PROJECT_DIR"])  # noqa: F821
CANONICAL = FIRMWARE_ROOT / "link" / "aius_teensy41.ld"
LAYOUT = FIRMWARE_ROOT / "lib" / "aius_ab" / "include" / "aius_ab_layout.h"

SLOT_BY_ENV_SUFFIX = {"-slot-a": "A", "-slot-b": "B"}


def layout_constant(text, name):
    match = re.search(rf"#define\s+{name}\s+UINT32_C\(0x([0-9A-Fa-f]+)\)",
                      text)
    if match is None:
        raise SystemExit(f"gen_slot_ldscript: {name} not found in {LAYOUT}")
    return int(match.group(1), 16)


def slot_window(slot):
    text = LAYOUT.read_text(encoding="utf-8")
    flash_base = layout_constant(text, "AIUS_AB_FLASH_BASE")
    head_bytes = layout_constant(text, "AIUS_AB_HEAD_BYTES")
    slot_bytes = layout_constant(text, "AIUS_AB_SLOT_BYTES")
    slot_a = flash_base + head_bytes
    base = slot_a if slot == "A" else slot_a + slot_bytes
    return base, slot_bytes


def generate():
    env_name = env["PIOENV"]  # noqa: F821
    slot = None
    for suffix, name in SLOT_BY_ENV_SUFFIX.items():
        if env_name.endswith(suffix):
            slot = name
    if slot is None:
        return  # not a slot env: the canonical script stands

    base, length = slot_window(slot)
    body = CANONICAL.read_text(encoding="utf-8")
    flash_line = re.compile(
        r"^\tFLASH \(rx\): ORIGIN = 0x60000000, LENGTH = 7936K$",
        re.MULTILINE)
    if len(flash_line.findall(body)) != 1:
        raise SystemExit(
            "gen_slot_ldscript: the canonical FLASH memory line moved; "
            "update this script's pattern alongside link/aius_teensy41.ld")
    patched = flash_line.sub(
        f"\tFLASH (rx): ORIGIN = 0x{base:08X}, LENGTH = 0x{length:X}"
        f" /* slot {slot}, generated by gen_slot_ldscript.py */",
        body)

    build_dir = Path(env.subst("$BUILD_DIR"))  # noqa: F821
    build_dir.mkdir(parents=True, exist_ok=True)
    target = build_dir / f"aius_teensy41_slot_{slot.lower()}.ld"
    if not target.exists() or target.read_text(encoding="utf-8") != patched:
        target.write_text(patched, encoding="utf-8")
    env.Replace(LDSCRIPT_PATH=str(target))  # noqa: F821


generate()
