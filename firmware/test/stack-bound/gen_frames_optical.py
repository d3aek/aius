"""Measures frames_optical.py: prologue frames of the symbols with no .su that
the stack-bound walk reaches, and the W3 leaves' inclusive depths.

usage: python3 gen_frames_optical.py [<env>]   (default teensy41-optical-slot-a)

A prologue frame is the push/stmdb register bytes, vpush bytes and the
immediate sp decrement; a register sp decrement marks the symbol dynamic
(written as None, which the suite treats as unlisted). A leaf's inclusive
depth follows its direct edges (veneers resolved, cycles cut); the leaves
are formatting-only and allocator functions whose indirect sites, if any,
are listed in the generated file's comment.
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
sys.path.insert(0, os.path.join(HERE, "..", "producer-isolation"))

import aius_walk as aw  # noqa: E402
import stack_bound as sb  # noqa: E402
from tables_optical import TABLES  # noqa: E402

REGS = re.compile(r"\{([^}]*)\}")


def count_regs(spec):
    n = 0
    for part in spec.split(","):
        part = part.strip()
        m = re.match(r"^([a-z]+)(\d+)-[a-z]+(\d+)$", part)
        n += (int(m.group(3)) - int(m.group(2)) + 1) if m else 1
    return n


def prologue(img, a):
    total = 0
    for (_ia, mn, ops) in img.insns[a][:16]:
        if mn.startswith("push") or (mn.startswith("stmdb") and ops.startswith("sp!")):
            total += 4 * count_regs(REGS.search(ops).group(1))
        elif mn.startswith("vpush"):
            m = REGS.search(ops).group(1)
            total += (8 if m.strip().startswith("d") else 4) * count_regs(m)
        elif mn.startswith(("sub", "subw")) and re.match(r"^sp, (sp, )?#", ops):
            total += int(re.search(r"#(\d+)", ops).group(1))
        elif mn.startswith("sub") and re.match(r"^sp, (sp, )?r", ops):
            return None
        elif mn.startswith("str") and re.search(r"\[sp, #-(\d+)\]!", ops):
            total += int(re.search(r"\[sp, #-(\d+)\]!", ops).group(1))
    return total


def main():
    env = sys.argv[1] if len(sys.argv) > 1 else "teensy41-optical-slot-a"
    from tables_stack import STACK
    d = os.path.join(HERE, "..", "..", ".pio", "build", env)
    img = aw.Image(os.path.join(d, "firmware.elf"), os.path.join(d, "firmware.map"))
    st = sb.StackTables(declared={}, leaf_inclusive={}, pass_entry=STACK.pass_entry,
                        main_roots=STACK.main_roots, handlers=STACK.handlers, chains=STACK.chains,
                        extra_sites=STACK.extra_sites)
    s = sb.StackBound(img, TABLES, st, sb.load_su([d]))
    s.sd_paths()
    s.exception_chain()
    declared, leaves, leaf_sites = {}, {}, set()
    for f in s.failures:
        m = re.match(r"stack-bound: no frame for (\S+) \((.*)\) \(\.su", f)
        if m:
            name, obj = m.group(1), m.group(2)
            a = [x for x in img.resolve(aw.base_name(name)) if obj in img.funcs[x].obj or not obj][0]
            key = (aw.base_name(name), sb.obj_stem(obj) + ".o" if obj else None)
            declared[key] = prologue(img, a)
        m = re.match(r"stack-bound: no declared inclusive depth for leaf (\S+)", f)
        if m:
            name = m.group(1)
            memo = {}

            def incl(x, stack=()):
                x = img.collapse(x)
                if x in stack:
                    return 0
                if x in memo:
                    return memo[x]
                if img.sites[x]:
                    leaf_sites.add(f"{img.funcs[x].name} {len(img.sites[x])}")
                fr = prologue(img, x) or 0
                v = fr + max((incl(b, stack + (x,)) for b in img.edges[x]), default=0)
                memo[x] = v
                return v
            leaves[name] = max(incl(a) for a in img.resolve(name))
    out = os.path.join(HERE, "frames_optical.py")
    with open(out, "w") as fh:
        fh.write('"""Generated by gen_frames_optical.py from the %s link; do not hand-edit.\n\n' % env)
        fh.write("Indirect sites under the leaves (not charged): %s\n\"\"\"\n\n" % (", ".join(sorted(leaf_sites)) or "none"))
        fh.write("DECLARED = {\n")
        for k in sorted(declared, key=str):
            if declared[k] is not None:
                fh.write(f"    {k!r}: {declared[k]},\n")
        fh.write("}\n\nDYNAMIC_PROLOGUE = %r\n\nLEAF_INCLUSIVE = {\n" % sorted(str(k) for k, v in declared.items() if v is None))
        for k in sorted(leaves):
            fh.write(f"    {k!r}: {leaves[k]},\n")
        fh.write("}\n")
    print("declared", len(declared), "leaves", len(leaves), "dynamic", [k for k, v in declared.items() if v is None])
    print("other failures", [f for f in s.failures if "no frame for" not in f and "inclusive depth" not in f][:20])
    print("walk failures", sorted(set(s.w.failures))[:20])


if __name__ == "__main__":
    main()
