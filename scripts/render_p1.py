def _csv_cell(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, (dict, list)):
        return _compact_json(value)
    return str(value)


def render_components(
    policy: Mapping[str, object],
    components: Iterable[Mapping[str, object]],
) -> bytes:
    """Render parsed component records as the deterministic review CSV."""
    families = {row["family"]: row for row in policy["families"]}
    output = io.StringIO(newline="")
    writer = csv.writer(
        output,
        dialect="excel",
        lineterminator="\n",
        quoting=csv.QUOTE_MINIMAL,
    )
    writer.writerow(COMPONENT_CSV_KEYS)
    for component in sorted(components, key=lambda row: row["block"]):
        family = families[component["block"]]
        generic = component["generic_policy"]
        writer.writerow(
            (
                _csv_cell(component["block"]),
                _csv_cell(component["status"]),
                _csv_cell(family["critical"]),
                _csv_cell(component["manufacturer"]),
                _csv_cell(component["mpn"]),
                _csv_cell(component["requirements"]),
                _csv_cell(component["alternatives"]),
                _csv_cell(component["selection_rationale"]),
                _csv_cell(component["authority_url"]),
                _csv_cell(component["manufacturer_request_id"]),
                _csv_cell(component["availability_request_id"]),
                _csv_cell(None if generic is None else generic["value"]),
                _csv_cell(None if generic is None else generic["package"]),
                _csv_cell(None if generic is None else generic["tolerance"]),
                _csv_cell(component["notes"]),
            )
        )
    return output.getvalue().encode("utf-8")


def render_supplemental_requests(
    requests: Iterable[Mapping[str, object]],
) -> bytes:
    """Render parsed request fragments as the deterministic aggregate JSON."""
    ordered_requests = [
        {key: request[key] for key in REQUEST_KEYS}
        for request in sorted(requests, key=lambda row: row["request_id"])
    ]
    aggregate = {"schema_version": "1.0.0", "requests": ordered_requests}
    return (json.dumps(aggregate, ensure_ascii=False, indent=2) + "\n").encode("utf-8")


def _parser() -> argparse.ArgumentParser:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--root", help="Aius project root")
    subparsers = parser.add_subparsers(dest="command", required=True)
    for command in (
        "functional-topology",
        "interfaces-and-states",
        "components",
        "supplemental-requests",
    ):
        command_parser = subparsers.add_parser(command)
        modes = command_parser.add_mutually_exclusive_group(required=True)
        modes.add_argument("--write", action="store_true")
        modes.add_argument("--check", action="store_true")
    return parser


def _load_json(root: Path, relative: Path) -> object:
    path = root / relative
    try:
        return json.loads(path.read_text(encoding="utf-8"))
    except FileNotFoundError as error:
        raise InputError(relative, "missing input") from error
    except (OSError, UnicodeError, json.JSONDecodeError) as error:
        raise InputError(relative, str(error)) from error


def _load_json_directory(root: Path, relative: Path) -> list[object]:
    directory = root / relative
    if not directory.is_dir():
        raise InputError(relative, "missing input directory")
    try:
        paths = sorted(directory.glob("*.json"), key=lambda path: path.name)
    except OSError as error:
        raise InputError(relative, str(error)) from error
    if not paths:
        raise InputError(relative, "contains no JSON inputs")
    return [_load_json(root, relative / path.name) for path in paths]


def _render_command(root: Path, command: str) -> tuple[Path, bytes]:
    try:
        if command == "functional-topology":
            document = _load_json(root, FUNCTIONAL_INPUT)
            return FUNCTIONAL_OUTPUT, render_functional_topology(document)
        if command == "interfaces-and-states":
            document = _load_json(root, INTERFACES_INPUT)
            return INTERFACES_OUTPUT, render_interfaces_and_states(document)
        if command == "components":
            policy = _load_json(root, POLICY_INPUT)
            components = _load_json_directory(root, COMPONENTS_INPUT)
            return COMPONENTS_OUTPUT, render_components(policy, components)
        if command == "supplemental-requests":
            requests = _load_json_directory(root, REQUESTS_INPUT)
            return REQUESTS_OUTPUT, render_supplemental_requests(requests)
    except InputError:
        raise
    except (KeyError, TypeError, ValueError) as error:
        primary = {
            "functional-topology": FUNCTIONAL_INPUT,
            "interfaces-and-states": INTERFACES_INPUT,
            "components": POLICY_INPUT,
            "supplemental-requests": REQUESTS_INPUT,
        }[command]
        raise InputError(primary, f"malformed input structure: {error}") from error
    raise AssertionError(f"unhandled command: {command}")


def _atomic_write(
    root: Path,
    relative: Path,
    payload: bytes,
    replace: Callable[[str, str], object],
) -> None:
    target = root / relative
    temporary = target.with_name(f".{target.name}.aius-{secrets.token_hex(8)}.tmp")
    descriptor: int | None = None
    owns_temporary = False
    try:
        descriptor = os.open(temporary, os.O_WRONLY | os.O_CREAT | os.O_EXCL, 0o600)
        owns_temporary = True
        with os.fdopen(descriptor, "wb", closefd=True) as handle:
            descriptor = None
            handle.write(payload)
            handle.flush()
            os.fsync(handle.fileno())
        replace(os.fspath(temporary), os.fspath(target))
    except OSError as error:
        if descriptor is not None:
            try:
                os.close(descriptor)
            except OSError:
                pass
        raise WriteError(relative, str(error)) from error
    finally:
        if owns_temporary:
            try:
                temporary.unlink()
            except FileNotFoundError:
                pass


def run(
    argv: list[str] | None = None,
    *,
    replace: Callable[[str, str], object] | None = None,
) -> int:
    arguments = _parser().parse_args(argv)
    root = (
        Path(arguments.root)
        if arguments.root is not None
        else Path(__file__).resolve().parents[1]
    )
    try:
        output, rendered = _render_command(root, arguments.command)
        target = root / output
        if arguments.check:
            try:
                current = target.read_bytes()
            except FileNotFoundError:
                print(f"AIUS-P1-RENDER-MISSING: {output.as_posix()}", file=sys.stderr)
                return 1
            except OSError as error:
                print(
                    f"AIUS-P1-RENDER-STALE: {output.as_posix()}: {error}",
                    file=sys.stderr,
                )
                return 1
            if current != rendered:
                print(f"AIUS-P1-RENDER-STALE: {output.as_posix()}", file=sys.stderr)
                return 1
        else:
            _atomic_write(root, output, rendered, os.replace if replace is None else replace)
        print(f"OK render {arguments.command} {output.as_posix()}")
        return 0
    except InputError as error:
        print(
            f"AIUS-P1-INPUT: {error.path.as_posix()}: {error.detail}",
            file=sys.stderr,
        )
        return 1
    except WriteError as error:
        print(
            f"AIUS-P1-RENDER-WRITE: {error.path.as_posix()}: {error.detail}",
            file=sys.stderr,
        )
        return 1


def main(argv: list[str] | None = None) -> int:
    return run(argv)


if __name__ == "__main__":
    raise SystemExit(main())
