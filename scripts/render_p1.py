class InputError(RuntimeError):
    """A required renderer input is missing, unreadable, or malformed."""

    def __init__(self, path: Path, detail: str) -> None:
        self.path = path
        self.detail = detail
        super().__init__(f"{path.as_posix()}: {detail}")


class WriteError(RuntimeError):
    """A rendered output could not be atomically replaced."""

    def __init__(self, path: Path, detail: str) -> None:
        self.path = path
        self.detail = detail
        super().__init__(f"{path.as_posix()}: {detail}")


def _compact_json(value: object) -> str:
    return json.dumps(
        value,
        ensure_ascii=False,
        sort_keys=True,
        separators=(",", ":"),
    )


def _scalar_text(value: object) -> str:
    if value is None:
        return ""
    if isinstance(value, bool):
        return "true" if value else "false"
    if isinstance(value, str):
        return value
    return json.dumps(value, ensure_ascii=False, separators=(",", ":"))


def _markdown_escape(text: str) -> str:
    return (
        text.replace("\\", "\\\\")
        .replace("|", "\\|")
        .replace("\r\n", "<br>")
        .replace("\r", "<br>")
        .replace("\n", "<br>")
    )


def _markdown_scalar(value: object) -> str:
    if isinstance(value, (dict, list)):
        text = _compact_json(value)
    else:
        text = _scalar_text(value)
    return _markdown_escape(text)


def _markdown_cell(value: object) -> str:
    if isinstance(value, list):
        return "<br>".join(_markdown_scalar(item) for item in value)
    return _markdown_scalar(value)


def _table(keys: Sequence[str], rows: Iterable[Mapping[str, object]]) -> list[str]:
    lines = [
        "| " + " | ".join(keys) + " |",
        "| " + " | ".join("---" for _ in keys) + " |",
    ]
    lines.extend(
        "| " + " | ".join(_markdown_cell(row[key]) for key in keys) + " |"
        for row in rows
    )
    return lines


def _render_markdown(
    title: str,
    sections: Iterable[tuple[str, Sequence[str], Iterable[Mapping[str, object]]]],
) -> bytes:
    lines = [f"# {title}", "", GENERATED_NOTICE]
    for heading, keys, rows in sections:
        lines.extend(("", f"## {heading}", ""))
        lines.extend(_table(keys, rows))
    return ("\n".join(lines) + "\n").encode("utf-8")


def render_functional_topology(document: Mapping[str, object]) -> bytes:
    """Render a parsed functional-topology document without filesystem access."""
    flows = document["flows"]
    if not isinstance(flows, list):
        raise TypeError("flows must be an array")
    sections = (
        ("Modes", MODE_KEYS, document["modes"]),
        ("Blocks", BLOCK_KEYS, document["blocks"]),
        ("Data flows", FLOW_KEYS, (row for row in flows if row["kind"] == "data")),
        (
            "Control flows",
            FLOW_KEYS,
            (row for row in flows if row["kind"] == "control"),
        ),
        ("Power flows", FLOW_KEYS, (row for row in flows if row["kind"] == "power")),
        ("Clock domains", CLOCK_DOMAIN_KEYS, document["clock_domains"]),
        ("Buffers and DMA ownership", BUFFER_KEYS, document["buffers"]),
        ("Latency boundaries", LATENCY_BOUNDARY_KEYS, document["latency_boundaries"]),
        (
            "Evidence",
            ("evidence_id",),
            ({"evidence_id": value} for value in document["evidence_ids"]),
        ),
    )
    return _render_markdown("Aius functional topology", sections)


